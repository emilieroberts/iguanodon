#![forbid(unsafe_code)]

//! CLI utility (`iguanodon-token-sync`) to synchronize Jetpack Compose Multiplatform 1.9+
//! Material 3 Expressive tokens (Colors, Shapes, and `MotionScheme` spring specs) with
//! Iguanodon's Rust and Kotlin Multiplatform theme layers.

use iguanodon_theme::ThemeDescriptor;

pub fn generate_kotlin_m3_expressive_tokens() -> String {
    let m3 = ThemeDescriptor::material3_expressive();
    format!(
        r#"// AUTO-GENERATED by iguanodon-token-sync — DO NOT EDIT MANUALLY
package iguanodon.compose.theme

object Material3ExpressiveTokens {{
    const val FAST_SPATIAL_DAMPING: Float = {:.2}f
    const val FAST_SPATIAL_STIFFNESS: Float = {:.1}f
    const val DEFAULT_SPATIAL_DAMPING: Float = {:.2}f
    const val DEFAULT_SPATIAL_STIFFNESS: Float = {:.1}f
    const val FAST_EFFECTS_DAMPING: Float = {:.2}f
    const val FAST_EFFECTS_STIFFNESS: Float = {:.1}f
    const val SHAPE_EXPONENT_P: Float = {:.2}f
    const val CORNER_RADIUS_MD: Float = {:.1}f
}}
"#,
        m3.motion.fast_spatial.damping_ratio,
        m3.motion.fast_spatial.stiffness,
        m3.motion.default_spatial.damping_ratio,
        m3.motion.default_spatial.stiffness,
        m3.motion.fast_effects.damping_ratio,
        m3.motion.fast_effects.stiffness,
        m3.shapes.shape_exponent_p,
        m3.shapes.radius_md,
    )
}

fn main() {
    print!("{}", generate_kotlin_m3_expressive_tokens());
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_kotlin_token_codegen_matches_expressive_spec() {
        let kt = generate_kotlin_m3_expressive_tokens();
        assert!(kt.contains("FAST_SPATIAL_STIFFNESS: Float = 800.0f"));
        assert!(kt.contains("SHAPE_EXPONENT_P: Float = 2.60f"));
    }
}
